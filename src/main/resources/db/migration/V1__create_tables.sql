CREATE TABLE motor_depots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE drivers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(200) NOT NULL,
    experience_years INTEGER NOT NULL CHECK (experience_years >= 0),
    motor_depot_id INTEGER REFERENCES motor_depots(id)
);

CREATE TABLE autos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR(20) NOT NULL UNIQUE,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    load_capacity_kg DOUBLE PRECISION NOT NULL
        CHECK (load_capacity_kg > 0),

    cargo_type VARCHAR(30) NOT NULL CHECK (
        cargo_type IN ('FOOD_LIQUID', 'PETROLEUM', 'BULK', 'PACKAGED')
    ),

    auto_condition VARCHAR(30) NOT NULL DEFAULT 'SERVICEABLE' CHECK (
        auto_condition IN ('SERVICEABLE', 'NEEDS_REPAIR', 'UNDER_REPAIR')
    ),

    motor_depot_id INTEGER REFERENCES motor_depots(id)
);

CREATE TABLE transport_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination VARCHAR(200) NOT NULL,
    cargo_weight_kg DOUBLE PRECISION NOT NULL
        CHECK (cargo_weight_kg > 0),

    cargo_type VARCHAR(30) NOT NULL CHECK (
        cargo_type IN ('FOOD_LIQUID', 'PETROLEUM', 'BULK', 'PACKAGED')
    ),

    request_status VARCHAR(30) NOT NULL DEFAULT 'NEW' CHECK (
        request_status IN ('NEW', 'ASSIGNED', 'COMPLETED', 'CANCELLED')
    ),

    motor_depot_id INTEGER REFERENCES motor_depots(id)
);

CREATE TABLE trips (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES transport_requests(id),
    driver_id INTEGER NOT NULL REFERENCES drivers(id),
    auto_id INTEGER NOT NULL REFERENCES autos(id),

    status VARCHAR(30) NOT NULL DEFAULT 'PLANNED' CHECK (
        status IN (
            'PLANNED', 'IN_PROGRESS', 'SUSPENDED',
            'COMPLETED', 'CANCELLED'
        )
    ),

    auto_condition_at_completion VARCHAR(30) CHECK (
        auto_condition_at_completion IN (
            'SERVICEABLE', 'NEEDS_REPAIR', 'UNDER_REPAIR'
        )
    ),

    transportation_cost DOUBLE PRECISION NOT NULL
        CHECK (transportation_cost >= 0),

    driver_payment DOUBLE PRECISION NOT NULL DEFAULT 0
        CHECK (driver_payment >= 0),

    motor_depot_id BIGINT REFERENCES motor_depots(id),

    CONSTRAINT completed_trip_has_condition CHECK (
        status <> 'COMPLETED'
        OR auto_condition_at_completion IS NOT NULL
    )
);

CREATE TABLE repair_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auto_id BIGINT NOT NULL REFERENCES autos(id),
    driver_id BIGINT NOT NULL REFERENCES drivers(id),
    trip_id BIGINT REFERENCES trips(id),
    description TEXT NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'NEW' CHECK (
        status IN ('NEW', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')
    ),

    motor_depot_id BIGINT REFERENCES motor_depots(id)
);

-- Водитель может быть назначен только на один активный рейс.
CREATE UNIQUE INDEX uq_active_trip_driver
    ON trips(driver_id)
    WHERE status IN ('PLANNED', 'IN_PROGRESS', 'SUSPENDED');

-- Автомобиль может быть назначен только на один активный рейс.
CREATE UNIQUE INDEX uq_active_trip_auto
    ON trips(auto_id)
    WHERE status IN ('PLANNED', 'IN_PROGRESS', 'SUSPENDED');

-- Повторное назначение заявки допускается после отмены рейса.
-- У заявки может быть только один неотменённый рейс.
CREATE UNIQUE INDEX uq_non_cancelled_trip_request
    ON trips(request_id)
    WHERE status <> 'CANCELLED';